#!/usr/bin/env python3
"""Reproduce the repository-pinned local observability deployment without package installers."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
CONFIG = HERE.parent / 'config'
DEFAULTS = json.loads((CONFIG / 'defaults.json').read_text())
sys.path.insert(0, str(HERE.parent / 'langfuse'))
from prepare_stack import prepare, render, write_private


def public_url():
    codespace = os.environ.get('CODESPACE_NAME')
    domain = os.environ.get('GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN', 'app.github.dev')
    return f'https://{codespace}-3000.{domain}' if codespace else 'http://localhost:3000'


def prepare_configs(state, workspace, codex_root, url, media_url=None):
    prepare(state, url, media_url)
    variables = dict(PYTHON=sys.executable, REPO=str(REPO), WORKSPACE_DATA=str(workspace),
                     CODEX_ROOT=str(codex_root), PUBLIC_URL=url, STATE=str(state))
    mcp = render(json.loads((CONFIG / 'mcp.template.json').read_text()), variables)
    write_private(state / 'mcp.json', mcp)
    profile = '# Generated by TTGL setup_local.py; source configuration is in the repository.\n'
    # Named profile files override the legacy profiles table in current Codex.
    profile += 'model_provider = "openai"\n\n[features]\nenable_request_compression = false\n'
    profile += '\n[mcp_servers.' + mcp['name'] + ']\n'
    profile += 'command = ' + json.dumps(mcp['command']) + '\nargs = ' + json.dumps(mcp['args']) + '\n'
    path = state / 'ttgl-observability.config.toml'
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as output:
        output.write(profile)
    return mcp, profile


def doctor(state):
    lock = json.loads((CONFIG / 'deployment.lock.json').read_text())
    checks = {'python_minimum': sys.version_info >= (3, 11)}
    observed = {'python': '.'.join(map(str, sys.version_info[:3]))}
    for name, command in {
        'codex_cli': ['codex', '--version'],
        'docker_engine': ['docker', 'version', '--format', '{{.Server.Version}}'],
        'docker_compose': ['docker', 'compose', 'version', '--short'],
    }.items():
        try:
            value = subprocess.check_output(command, text=True, stderr=subprocess.DEVNULL).strip()
            observed[name] = value.removeprefix('codex-cli ')
            checks[name] = True
        except (OSError, subprocess.CalledProcessError):
            checks[name] = False
    checks['tested_codex_version'] = observed.get('codex_cli') == lock['tested_host']['codex_cli']
    subset=json.loads((CONFIG/'headroom-subset.lock.json').read_text())
    checks['headroom_subset_matches_pin']=all(hashlib.sha256((HERE/'vendor/headroom'/name).read_bytes()).hexdigest()==digest for name,digest in subset['vendored_files'].items())
    checks['prepared_compose'] = (state / 'compose.json').exists()
    design = json.loads((CONFIG / 'design-system.lock.json').read_text())
    assets = REPO / design['local_directory']
    checks['private_design_system_synced'] = all((assets / name).exists() and hashlib.sha256((assets / name).read_bytes()).hexdigest() == digest for name, digest in design['files'].items())
    if checks['prepared_compose']:
        stack = json.loads((state / 'compose.json').read_text())
        actual_images = {name: service['image'] for name, service in stack['services'].items()}
        checks['compose_matches_image_lock'] = actual_images == {name: item['image'] for name, item in lock['images'].items()}
        checks['no_automatic_pulls'] = all(service.get('pull_policy') == 'never' for service in stack['services'].values())
    images = {}
    for name, entry in lock['images'].items():
        result = subprocess.run(['docker', 'image', 'inspect', entry['image'], '--format', '{{.Id}}'], capture_output=True, text=True) if shutil.which('docker') else None
        images[name] = bool(result and result.returncode == 0)
    result = dict(ready=all(checks.values()) and all(images.values()), checks=checks, observed=observed,
                  tested=lock['tested_host'], locked_images_present=images,
                  note='No software is installed or updated. Version differences are not silently repaired.')
    print(json.dumps(result, indent=2))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'configure-codex', 'configure-cli', 'doctor', 'pull', 'start', 'status', 'dashboard'])
    parser.add_argument('--state', type=Path, default=REPO / DEFAULTS['state_directory'])
    parser.add_argument('--workspace-data', type=Path, default=REPO / DEFAULTS['workspace_directory'])
    parser.add_argument('--codex-root', type=Path, default=Path(DEFAULTS['codex_directory']).expanduser())
    parser.add_argument('--langfuse-url', default=public_url())
    parser.add_argument('--media-url', help='Override the browser-facing S3 URL; defaults to the Codespaces forwarded port or localhost:9090')
    args = parser.parse_args()
    args.state, args.workspace_data, args.codex_root = args.state.resolve(), args.workspace_data.resolve(), args.codex_root.resolve()
    if args.action in ('prepare', 'configure-codex'):
        mcp, profile = prepare_configs(args.state, args.workspace_data, args.codex_root, args.langfuse_url, args.media_url)
        subprocess.run(['docker', 'compose', '-f', str(args.state / 'compose.json'), 'config', '--quiet'], check=True)
        if args.action == 'configure-codex':
            config_home = Path(os.environ.get('CODEX_HOME', str(Path.home() / '.codex')))
            config_home.mkdir(parents=True, exist_ok=True)
            path = config_home / 'ttgl-observability.config.toml'
            if path.exists() and not path.read_text().startswith('# Generated by TTGL setup_local.py;'):
                raise ValueError('Refusing to overwrite an unowned Codex profile')
            subprocess.run(['codex', 'mcp', 'add', mcp['name'], '--', mcp['command'], *mcp['args']], check=True)
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, 'w') as output:
                output.write(profile)
            from install_live_codex import install
            install(config_home / 'config.toml', 'headroom-lossless', args.state)
            print('Installed analyst tools with the built-in OpenAI provider. Capture/compression requires the explicit ttgl-capture-experimental profile or codex_traced.py. Backup receipt retained privately.')
    elif args.action == 'configure-cli':
        path = Path.home() / '.local/bin/ttgl'
        header = '#!/usr/bin/env python3\n# Generated by TTGL setup_local.py; analyst CLI launcher.\n'
        if path.exists() and not path.read_text().startswith(header):
            raise ValueError('Refusing to overwrite an unowned ttgl executable')
        path.parent.mkdir(parents=True, exist_ok=True)
        source = header + 'import os, sys\nos.execv(' + repr(sys.executable) + ', [' + repr(sys.executable) + ', ' + repr(str(HERE / 'analyst_cli.py')) + '] + sys.argv[1:])\n'
        path.write_text(source)
        path.chmod(0o755)
        print('Installed ' + str(path) + '; run ttgl tools for the shared MCP/CLI contract.')
    elif args.action == 'doctor':
        if not doctor(args.state)['ready']:
            raise SystemExit(1)
    elif args.action == 'pull':
        # Explicit operation only: use the fixed graph, never a floating release.
        subprocess.run(['docker', 'compose', '-f', str(args.state / 'compose.json'), 'pull', '--policy', 'always'], check=True)
    elif args.action == 'start':
        command = [sys.executable, str(HERE / 'start_local.py'), '--state', str(args.state),
                   '--workspace-data', str(args.workspace_data), '--codex-root', str(args.codex_root), '--langfuse-url', args.langfuse_url]
        os.execv(command[0], command)
    elif args.action == 'status':
        subprocess.run(['docker', 'compose', '-f', str(args.state / 'compose.json'), 'ps'], check=True)
        if (args.state / 'runtime.json').exists():
            print((args.state / 'runtime.json').read_text())
    elif args.action == 'dashboard':
        from native_dashboard import configure
        configure(args.state / 'local-access.json', args.state / 'native-dashboard.json')


if __name__ == '__main__':
    main()
